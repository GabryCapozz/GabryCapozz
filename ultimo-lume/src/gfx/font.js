const LINE_H = 10;
const SPACE_W = 3;

class BitmapFont {
  constructor() {
    this.glyphs = new Map();
    let x = 0;
    for (const [ch, def] of Object.entries(G)) {
      const rows = def.split('/');
      const w = Math.max(...rows.map((r) => r.length));
      this.glyphs.set(ch, { rows, w, x });
      x += w + 1;
    }
    this.atlasW = x;
    this.atlases = new Map();
    this.lineH = LINE_H;
  }

  atlas(color) {
    let a = this.atlases.get(color);
    if (a) return a;
    a = makeCanvas(this.atlasW, 9);
    const ctx = a.getContext('2d');
    ctx.fillStyle = color;
    for (const g of this.glyphs.values()) {
      g.rows.forEach((row, y) => {
        for (let i = 0; i < row.length; i++) if (row[i] === '#') ctx.fillRect(g.x + i, y, 1, 1);
      });
    }
    this.atlases.set(color, a);
    return a;
  }

  charWidth(ch) {
    if (ch === ' ') return SPACE_W;
    const g = this.glyphs.get(ch) || this.glyphs.get('?');
    return g.w;
  }

  // Width in pixels; supports {highlight} markup (braces are not drawn).
  measure(text) {
    let w = 0;
    for (const ch of text) {
      if (ch === '{' || ch === '}') continue;
      w += this.charWidth(ch) + 1;
    }
    return Math.max(0, w - 1);
  }

  // Draw text. `{word}` renders in the highlight colour.
  draw(ctx, text, x, y, color = P.sand, opts = {}) {
    const { align = 'left', shadow = P.ink, hi = P.gold, alpha = 1 } = opts;
    text = String(text);
    let cx = Math.round(x);
    if (align === 'center') cx = Math.round(x - this.measure(text) / 2);
    else if (align === 'right') cx = Math.round(x - this.measure(text));
    y = Math.round(y);
    if (alpha !== 1) ctx.globalAlpha = alpha;
    if (shadow) this._run(ctx, text, cx, y + 1, shadow, shadow);
    this._run(ctx, text, cx, y, color, hi);
    if (alpha !== 1) ctx.globalAlpha = 1;
    return this.measure(text);
  }

  _run(ctx, text, x, y, color, hi) {
    let useHi = false;
    const base = this.atlas(color);
    const hiAtlas = this.atlas(hi);
    for (const ch of text) {
      if (ch === '{') { useHi = true; continue; }
      if (ch === '}') { useHi = false; continue; }
      if (ch === ' ') { x += SPACE_W + 1; continue; }
      const g = this.glyphs.get(ch) || this.glyphs.get('?');
      ctx.drawImage(useHi ? hiAtlas : base, g.x, 0, g.w, 9, x, y, g.w, 9);
      x += g.w + 1;
    }
  }

  // Word-wrap into lines not exceeding maxW. Keeps {markup} balanced per line.
  wrap(text, maxW) {
    const out = [];
    for (const para of String(text).split('\n')) {
      const words = para.split(' ');
      let line = '';
      for (const word of words) {
        const test = line ? line + ' ' + word : word;
        if (this.measure(test) > maxW && line) {
          out.push(line);
          line = word;
        } else line = test;
      }
      out.push(line);
    }
    // re-balance highlight braces across line breaks
    let open = false;
    return out.map((l) => {
      let s = open ? '{' + l : l;
      for (const ch of l) {
        if (ch === '{') open = true;
        else if (ch === '}') open = false;
      }
      if (open) s += '}';
      return s;
    });
  }
}

export const font = new BitmapFont();
